// Fallback: first letter badge
function FallbackIcon({ name, size }: { name: string; size: number }) {
    return (
        <div
            className="flex items-center justify-center font-mono font-bold uppercase"
            style={{ width: size, height: size, fontSize: size * 0.45, borderRadius: 'var(--radius-subtle)', background: 'var(--color-border)', color: 'var(--color-muted)' }}
        >
            {name.charAt(0)}
        </div>
    );
}

export function TechIcon({ name, size = 20, className, showLabel = false }: TechIconProps) {
    const renderIcon = icons[name];

    return (
        <div className={clsx('inline-flex items-center gap-2', className)}>
            <div className="flex items-center justify-center" style={{ color: 'var(--color-muted)' }}>
                {renderIcon ? renderIcon(size) : <FallbackIcon name={name} size={size} />}
            </div>
            {showLabel && (
                <span className="type-caption" style={{ color: 'var(--color-muted)' }}>{name}</span>
            )}
        </div>
    );
}

export function TechStack({ techs, iconSize = 18, showLabels = true }: { techs: string[]; iconSize?: number; showLabels?: boolean }) {
    return (
        <div className="flex flex-wrap" style={{ gap: 'var(--space-3)' }}>
            {techs.map((tech) => (
                <div
                    key={tech}
                    className="flex items-center"
                    style={{
                        gap: 'var(--space-2)',
                        border: '1px solid var(--color-border)',
                        padding: 'var(--space-2) var(--space-3)',
                        transition: `border-color var(--duration-base) var(--ease-out), background var(--duration-base) var(--ease-out)`,
                    }}
                    onMouseEnter={(e) => { e.currentTarget.style.borderColor = 'rgba(255,255,255,0.15)'; e.currentTarget.style.background = 'rgba(255,255,255,0.05)'; }}
                    onMouseLeave={(e) => { e.currentTarget.style.borderColor = 'var(--color-border)'; e.currentTarget.style.background = 'transparent'; }}
                >
                    <TechIcon name={tech} size={iconSize} />
                    {showLabels && (
                        <span className="type-caption" style={{ color: 'var(--color-muted)' }}>{tech}</span>
                    )}
                </div>
            ))}
        </div>
    );
}
